case "$recorded" in
  *@sha256:????????????????????????????????????????????????????????????????) ;;
  *) echo "$1 holds no image digest: '$recorded'" >&2; exit 1 ;;
esac
if [ "$recorded" != "$2" ]; then
  echo "ci verified $recorded but the registry resolves this commit's tag to $2" >&2
  exit 1
fi
