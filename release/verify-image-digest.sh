# Refuses an image that is not the one ci verified: RECORDED is the file ci
# wrote, DEPLOYED is what the registry resolves the tag to now.
set -euo pipefail

if [ "$#" -ne 2 ]; then
  echo "usage: $0 RECORDED_FILE DEPLOYED" >&2
  exit 2
fi

